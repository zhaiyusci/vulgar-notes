/* Download exact, pinned CSL XML; no runtime network access is required. */
const { createHash } = require('node:crypto');
const { mkdir, writeFile } = require('node:fs/promises');
const path = require('node:path');

const output = path.resolve(__dirname, '../src/csl');
// CSL recommends its validated version branches for downstream distributions.
// Updating these commits is an explicit source change, never part of a build.
const revisions = {
  styles: '3684ae0ae6e93246d02858658e55009508428f5d',
  locales: '6b70fe79264543aa538f8927fcc98d5b72425a94',
};
const styles = {
  ieee: 'ieee.csl',
  // Upstream renamed the independent Vancouver/NLM style in January 2026;
  // dependent/vancouver-nlm.csl now resolves to this current parent.
  vancouver: 'nlm-citation-sequence.csl',
  apa: 'apa.csl',
  chicago: 'chicago-notes-bibliography.csl',
  gbt7714: 'china-national-standard-gb-t-7714-2025-numeric.csl',
};
const locales = { 'en-US': 'locales-en-US.xml', 'zh-CN': 'locales-zh-CN.xml' };
const licenseUrl = 'https://creativecommons.org/licenses/by-sa/3.0/legalcode.txt';
const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');

async function request(url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'Vulgar-Notes-CSL-assets' },
    signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error(`${response.status} downloading ${url}`);
  return response;
}

async function source(repository, filename) {
  const revision = revisions[repository];
  // The contents API avoids depending on access to raw.githubusercontent.com.
  const response = await request(
    `https://api.github.com/repos/citation-style-language/${repository}/contents/${filename}?ref=${revision}`
  );
  const data = await response.json();
  if (data.encoding !== 'base64' || typeof data.content !== 'string') {
    throw new Error(`Expected base64 source for ${repository}/${filename}`);
  }
  const bytes = Buffer.from(data.content, 'base64');
  const xml = bytes.toString('utf8');
  if (!Buffer.from(xml, 'utf8').equals(bytes)) throw new Error(`Invalid UTF-8: ${filename}`);
  return {
    xml,
    metadata: {
      repository: `https://github.com/citation-style-language/${repository}`,
      revision,
      file: filename,
      source: `https://github.com/citation-style-language/${repository}/blob/${revision}/${filename}`,
      download: `https://raw.githubusercontent.com/citation-style-language/${repository}/${revision}/${filename}`,
      sha256: sha256(bytes),
      bytes: bytes.length,
      license: 'CC-BY-SA-3.0',
    },
  };
}

async function main() {
  const downloadedStyles = await Promise.all(Object.entries(styles).map(async ([id, filename]) => {
    const result = await source('styles', filename);
    if (!result.xml.includes('<style ') || result.xml.includes('rel="independent-parent"')) {
      throw new Error(`Expected independent CSL style: ${filename}`);
    }
    const title = result.xml.match(/<title>([\s\S]*?)<\/title>/)?.[1];
    if (!title) throw new Error(`Style title missing: ${filename}`);
    return [id, { ...result, metadata: { ...result.metadata, title } }];
  }));
  const downloadedLocales = await Promise.all(Object.entries(locales).map(async ([id, filename]) => {
    const result = await source('locales', filename);
    if (!result.xml.includes(`xml:lang="${id}"`)) throw new Error(`Wrong locale: ${filename}`);
    return [id, result];
  }));
  const [stylesReadme, localesReadme, licenseResponse] = await Promise.all([
    source('styles', 'README.md'),
    source('locales', 'README.md'),
    request(licenseUrl),
  ]);
  const licenseBytes = Buffer.from(await licenseResponse.arrayBuffer());
  if (!licenseBytes.toString('utf8').includes('Attribution-ShareAlike 3.0 Unported')) {
    throw new Error('Unexpected Creative Commons legal code');
  }
  if (!stylesReadme.xml.includes('Attribution-ShareAlike 3.0') ||
      !localesReadme.xml.includes('Attribution-ShareAlike 3.0')) {
    throw new Error('Upstream license changed; review notices before updating');
  }

  await mkdir(output, { recursive: true });
  const moduleText = [
    '// Generated by scripts/update-csl-assets.cjs. Do not edit the embedded XML.',
    '// Citation Style Language project: https://citationstyles.org/',
    '// XML assets: CC-BY-SA-3.0; see NOTICE.md, manifest.json, and LICENSE-CC-BY-SA-3.0.txt.',
    '// Source author, contributor, translator, and rights metadata are preserved in full.',
    'export const cslStyles = {',
    ...downloadedStyles.map(([id, { xml }]) => `  ${JSON.stringify(id)}: ${JSON.stringify(xml)},`),
    '} as const;',
    '',
    'export const cslLocales = {',
    ...downloadedLocales.map(([id, { xml }]) => `  ${JSON.stringify(id)}: ${JSON.stringify(xml)},`),
    '} as const;',
    '',
  ].join('\n');
  const manifest = {
    project: 'Citation Style Language',
    homepage: 'https://citationstyles.org/',
    license: 'CC-BY-SA-3.0',
    format: 'Exact upstream UTF-8 XML, embedded as TypeScript string literals without XML modifications',
    styles: Object.fromEntries(downloadedStyles.map(([id, result]) => [id, result.metadata])),
    locales: Object.fromEntries(downloadedLocales.map(([id, result]) => [id, result.metadata])),
    attributionSources: { styles: stylesReadme.metadata, locales: localesReadme.metadata },
    licenseText: { source: licenseUrl, sha256: sha256(licenseBytes), bytes: licenseBytes.length },
  };
  await Promise.all([
    writeFile(path.join(output, 'assets.ts'), moduleText),
    writeFile(path.join(output, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`),
    writeFile(path.join(output, 'UPSTREAM-STYLES-README.md'), stylesReadme.xml),
    writeFile(path.join(output, 'UPSTREAM-LOCALES-README.md'), localesReadme.xml),
    writeFile(path.join(output, 'LICENSE-CC-BY-SA-3.0.txt'), licenseBytes),
  ]);
  for (const [id, result] of downloadedStyles) console.log(`${id}: ${result.metadata.title}`);
  console.log(`Vendored ${downloadedStyles.length} styles and ${downloadedLocales.length} locales.`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
