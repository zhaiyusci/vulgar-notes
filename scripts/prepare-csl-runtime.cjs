const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const directory=path.join(root,'vendor/csl-lua/runtime');
const manifest=JSON.parse(fs.readFileSync(path.join(directory,'manifest.json'),'utf8'));
for(const record of [...manifest.files,...manifest.licenseFiles]){
  const base=record.path.startsWith('licenses/csl-lua/')?root:directory;
  const filename=path.resolve(base,record.path);
  if(!filename.startsWith(base+path.sep))throw Error('CSL runtime source path escapes its directory');
  const contents=fs.readFileSync(filename);
  if(record.bytes!==contents.length||record.sha256!==crypto.createHash('sha256').update(contents).digest('hex'))throw Error('CSL runtime source hash mismatch: '+record.path);
}
const bytes=fs.readFileSync(path.join(directory,'lua-csl.wasm'));
if(manifest.wasm.bytes!==bytes.length||manifest.wasm.sha256!==crypto.createHash('sha256').update(bytes).digest('hex'))throw Error('CSL runtime hash mismatch');
const generated='// Generated by scripts/prepare-csl-runtime.cjs. Do not edit.\n'
  +'// Runtime sources and build instructions: vendor/csl-lua/runtime/.\n'
  +'export const runtimeBase64='+JSON.stringify(bytes.toString('base64'))+';\n';
const destination=path.join(root,'src/csl-lua/runtime.generated.ts');
fs.mkdirSync(path.dirname(destination),{recursive:true});
if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==generated)fs.writeFileSync(destination,generated);
console.log('Prepared local Lua CSL runtime ('+bytes.length+' bytes).');
