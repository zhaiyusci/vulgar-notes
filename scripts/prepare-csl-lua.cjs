// Embed only pinned processor code and Unicode tables. Document data is passed
// to the runtime as JSON; it is never concatenated into these Lua modules.
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const vendor=path.join(root,'vendor/csl-lua');
const modules=JSON.parse(fs.readFileSync(path.join(vendor,'modules.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(vendor,'files.json'),'utf8'));
function read(relative){
  const resolved=path.resolve(vendor,relative);
  if(!resolved.startsWith(vendor+path.sep))throw Error('CSL asset path escapes vendor directory');
  const contents=fs.readFileSync(resolved),record=manifest.files[relative];
  if(!record||record.bytes!==contents.length||record.sha256!==crypto.createHash('sha256').update(contents).digest('hex'))throw Error('CSL asset hash mismatch: '+relative);
  return contents.toString('utf8');
}
const luaModules=Object.fromEntries(Object.entries(modules).map(([name,file])=>[name,read(file)]));
const dataFiles=Object.fromEntries(Object.entries(manifest.files).filter(([,file])=>file.dataFile).map(([file,record])=>[record.dataFile,read(file)]));
const generated='// Generated by scripts/prepare-csl-lua.cjs. Do not edit.\n// Third-party notices: licenses/csl-lua/NOTICE.txt.\n'
  +'export const luaModules: Readonly<Record<string,string>> = '+JSON.stringify(luaModules)+';\n'
  +'export const dataFiles: Readonly<Record<string,string>> = '+JSON.stringify(dataFiles)+';\n';
const output=path.join(root,'src/csl-lua/assets.generated.ts');
fs.mkdirSync(path.dirname(output),{recursive:true});
if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==generated)fs.writeFileSync(output,generated);
console.log('Prepared '+Object.keys(luaModules).length+' Lua modules and '+Object.keys(dataFiles).length+' Unicode data files.');
