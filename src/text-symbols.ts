export const textSymbols:readonly TextSymbol[]=Object.freeze(fixedSymbols.map(([command,value])=>Object.freeze({command,value})));
const values=new Map(textSymbols.map(symbol=>[symbol.command,symbol.value]));
/** Look up a complete control-word name without its leading backslash. */
export function textSymbolValue(command:string):string|undefined {return values.get(command);}

